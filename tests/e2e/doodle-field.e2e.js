// Doodles: drawn to the screen, not tiled; redrawn on resize; gone when Plain; light and dark.
import { startApp, openDevice, makeChecker, seedLocal } from "./harness.js";
import { FOODS_JS, stateBlob, localState } from "./helpers.js";
const DIR = new URL("../..", import.meta.url).pathname;
const t = makeChecker(); const sleep = ms => new Promise(r => setTimeout(r, ms));
const app = await startApp(DIR, null, { "foods_data.js": FOODS_JS, "manifest.json": "{}" });
const blob = stateBlob(); blob.settings = { ...(blob.settings || {}), backgroundPattern: "doodles" };
const dev = await openDevice(app, { width: 420, height: 900, mobile: false, inject: `if (!localStorage.getItem("insulinBuddy.v2")) { ${seedLocal(blob)} }`, wait: 1800 });
const info = () => dev.eval(`(() => { const h = document.getElementById("bg-doodles"); const s = h && h.querySelector("svg"); const cs = h && getComputedStyle(h); return { has: !!s, uses: s ? s.querySelectorAll("use").length : 0, w: s ? +s.getAttribute("width") : 0, pos: cs && cs.position, bodyImg: getComputedStyle(document.body).backgroundImage, flag: document.documentElement.getAttribute("data-pattern-field"), color: cs && cs.color, op: cs && cs.opacity, z: cs && cs.zIndex }; })()`);
t.section("DOODLES: drawn for the screen, with no tile");
let a = await info();
t.check("a doodle layer exists, fixed behind the app, with lots of doodles", a.has && a.pos === "fixed" && a.z === "-1" && a.uses > 300, JSON.stringify(a));
t.check("the old repeating tile is switched off on the page", a.bodyImg === "none" && a.flag === "doodles", a.bodyImg);
t.check("the layer is as wide as the screen", a.w === 420, String(a.w));
await dev.resize(1280, 800); await sleep(700);
let b = await info();
t.check("resizing redraws it for the new width (more doodles, wider)", b.w === 1280 && b.uses > a.uses, JSON.stringify({ aw: a.w, bw: b.w, au: a.uses, bu: b.uses }));
await dev.eval(`document.documentElement.setAttribute("data-theme","dark")`); await sleep(100);
let c = await info();
t.check("dark mode draws it in the light ink, very faintly", c.color === "rgb(236, 234, 227)" && +c.op < 0.1, JSON.stringify(c));
await dev.eval(`document.documentElement.setAttribute("data-theme","light")`);
t.check("no JS errors", dev.errors.length === 0, JSON.stringify(dev.errors));
await dev.tab("settings"); await sleep(250);
await dev.eval(`document.querySelector('#settings-segmented [data-seg="general"]').click()`); await sleep(300);
await dev.click('#bg-pattern-grid [data-pattern="none"]'); await sleep(300);
let d = await info();
t.check("choosing Plain removes the layer", !d.has && d.flag === null, JSON.stringify(d));
await dev.click('#bg-pattern-grid [data-pattern="doodles"]'); await sleep(300);
await dev.click('#bg-pattern-size [data-size="large"]'); await sleep(300);
let e = await info();
t.check("choosing Doodles again, in Large, draws fewer, bigger ones", e.has && e.uses < b.uses, JSON.stringify({ e: e.uses, b: b.uses }));
t.section("ABSTRACT: the same, with the artwork's shapes");
await dev.click('#bg-pattern-grid [data-pattern="abstract"]'); await sleep(400);
const abs = () => dev.eval(`(() => { const h = document.getElementById("bg-abstract"); const cs = h && getComputedStyle(h); const l = h && h.querySelector(".l"); return { has: !!(h && h.querySelector("svg")), uses: h ? h.querySelectorAll("use").length : 0, w: h ? +h.querySelector("svg").getAttribute("width") : 0, pos: cs && cs.position, op: cs && +cs.opacity, line: l ? getComputedStyle(l).fill : null, flag: document.documentElement.getAttribute("data-pattern-field"), bodyImg: getComputedStyle(document.body).backgroundImage, doodles: !!document.getElementById("bg-doodles") }; })()`);
let f = await abs();
t.check("an Abstract layer replaces the doodle one, fixed and faded", f.has && f.pos === "fixed" && f.op === 0.2 && f.flag === "abstract" && !f.doodles, JSON.stringify(f));
t.check("it has many shapes, and the old tile is off", f.uses > 20 && f.bodyImg === "none", JSON.stringify(f));
t.check("the linework takes the pale grey from the page", f.line === "rgb(147, 153, 157)", String(f.line));
const w1 = f.w, u1 = f.uses;
await dev.resize(420, 900); await sleep(700);
f = await abs();
t.check("resizing redraws it for the new width", f.w === 420 && f.w !== w1 && f.uses < u1, JSON.stringify({ w1, u1, f }));
await dev.eval(`document.documentElement.setAttribute("data-theme","dark")`); await sleep(100);
f = await abs();
t.check("dark mode fades it a little less and greys the linework differently", f.op === 0.18 && f.line === "rgb(110, 112, 112)", JSON.stringify(f));
t.check("no JS errors", dev.errors.length === 0, JSON.stringify(dev.errors));
dev.close(); await app.close(); process.exit(0);
